"""Claim-level attribution: which retrieved source supports which answer sentence.

The layer between "the answer is grounded somewhere in the context" and "this
particular claim is backed by this particular citation". It takes an answer,
splits it into claims, and reports for each claim whether the available evidence
supports it and which cited sources do.

**Two different questions, deliberately not merged:**

- ``supported`` -- the claim's tokens are covered by the **context** (the
  evidence retrieval actually produced). This is a property of the claim against
  the available material, and it is exactly what makes the two rates different
  numbers rather than two names for one.
- ``attributed`` -- the claim is covered by at least one **citation** (the
  structured ``Citation`` objects the pipeline projected out of that same
  Context). With no citations, a claim can be supported and unattributed at
  once; with a citation that does not cover it, the same.

Citations are only ever read from the structured ``Citation`` objects. This
module never parses an answer for ``[1]``, ``doc_a::0``, or any other marker,
and no such convention exists anywhere in ZMRAG.

**What this is not.** Claim extraction is sentence splitting, nothing more:
no clause decomposition, no subject/predicate analysis, no coreference. Support
is lexical token overlap, nothing more: no entailment, no NLI, no embedding, no
semantic similarity, no LLM judge, no third-party library. The known
consequences are recorded rather than papered over -- a negation
("LRU evicts..." vs "LRU never evicts...") and a paraphrase both score the same
as the original, because every token is present either way.
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from collections.abc import Sequence
from dataclasses import dataclass

from .citations import Citation
from .context import Context
from .schema import _nonempty_str
from .text import safe_ratio, split_sentences, token_coverage, tokenize_text
from .tokenizers import SimpleTokenizer, Tokenizer

