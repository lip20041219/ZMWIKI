#: A claim counts as supported/attributed when at least this share of its unique
#: tokens is found in the support text. Fixed, never tuned against a dataset.
DEFAULT_ATTRIBUTION_THRESHOLD = 0.5


@dataclass(frozen=True)
class Claim:
    """One answer sentence treated as one claim.

    ``claim_id`` is generated by the extractor (``"claim-0"``, ``"claim-1"``,
    ...) and is unique within an answer. ``sentence_index`` is the claim's
    position in that answer's sentence sequence -- the same order the sentences
    appear in, with empty pieces already dropped. ``text`` is the sentence as it
    was written, terminator included.
    """

    claim_id: str
    text: str
    sentence_index: int

    def __post_init__(self) -> None:
        _nonempty_str(self.claim_id, "claim_id")
        _nonempty_str(self.text, "claim text")
        if isinstance(self.sentence_index, bool) or not isinstance(self.sentence_index, int):
            raise TypeError(
                f"sentence_index must be an int, got {type(self.sentence_index).__name__}"
            )
        if self.sentence_index < 0:
            raise ValueError(f"sentence_index must be >= 0, got {self.sentence_index}")

    def to_dict(self) -> dict[str, object]:
        return {
            "claim_id": self.claim_id,
            "text": self.text,
            "sentence_index": self.sentence_index,
        }


@dataclass(frozen=True)
class ClaimAttribution:
    """One claim's verdict: is it supported, and which citations carry it.

    ``support_score`` is the claim's token coverage against the context, in
    [0, 1]; ``supported`` is that score at or above the threshold. The two are
    both reported so a reader can see how close a miss was.

    ``supporting_citation_ids`` holds the ``chunk_id`` of every citation whose
    own coverage of the claim reaches the threshold, in citation input order,
    with duplicates collapsed to their first occurrence. If several citations
    qualify, all of them are kept -- attribution is not a single-source vote.
    """

    claim_id: str
    supported: bool
    supporting_citation_ids: tuple[str, ...]
    support_score: float

    def __post_init__(self) -> None:
        _nonempty_str(self.claim_id, "claim_id")
        if not isinstance(self.supported, bool):
            raise TypeError(f"supported must be a bool, got {type(self.supported).__name__}")
        if isinstance(self.support_score, bool) or not isinstance(
            self.support_score, (int, float)
        ):
            raise TypeError(
                f"support_score must be a float, got {type(self.support_score).__name__}"
            )
        if not 0.0 <= self.support_score <= 1.0:
            raise ValueError(f"support_score must be in [0, 1], got {self.support_score!r}")
        if not isinstance(self.supporting_citation_ids, tuple):
            raise TypeError(
                "supporting_citation_ids must be a tuple of str, got "
                f"{type(self.supporting_citation_ids).__name__}"
            )
        seen: set[str] = set()
        for citation_id in self.supporting_citation_ids:
            _nonempty_str(citation_id, "supporting citation id")
            if citation_id in seen:
                raise ValueError(f"duplicate supporting citation id: {citation_id!r}")
            seen.add(citation_id)

    @property
    def attributed(self) -> bool:
        """At least one citation supports this claim."""
        return bool(self.supporting_citation_ids)

    def to_dict(self) -> dict[str, object]:
        return {
            "claim_id": self.claim_id,
            "supported": self.supported,
            "attributed": self.attributed,
            "supporting_citation_ids": list(self.supporting_citation_ids),
            "support_score": self.support_score,
        }


@dataclass(frozen=True)
class AttributionResult:
    """Every claim of one answer, plus the two rates over them.

    ``supported_claim_rate`` and ``attributed_claim_rate`` are separate numbers
    and are never combined into a single score: an answer can be fully supported
    by its context and carry no citations at all, and that is a different
    finding from an answer whose citations do not cover it.

    With no claims both rates are 0.0 -- an empty answer attributes nothing, and
    no denominator is ever zero.
    """

    claims: tuple[ClaimAttribution, ...]
    supported_claim_rate: float
    attributed_claim_rate: float
    total_claims: int
    supported_claims: int
    attributed_claims: int
    mean_support_score: float

    def __post_init__(self) -> None:
        if not isinstance(self.claims, tuple):
            raise TypeError(f"claims must be a tuple, got {type(self.claims).__name__}")
        for claim in self.claims:
            if not isinstance(claim, ClaimAttribution):
                raise TypeError(
                    f"each claim must be a ClaimAttribution, got {type(claim).__name__}"
                )
        for name, value in (
            ("supported_claim_rate", self.supported_claim_rate),
            ("attributed_claim_rate", self.attributed_claim_rate),
            ("mean_support_score", self.mean_support_score),
        ):
            if isinstance(value, bool) or not isinstance(value, (int, float)):
                raise TypeError(f"{name} must be a float, got {type(value).__name__}")
            if not 0.0 <= value <= 1.0:
                raise ValueError(f"{name} must be in [0, 1], got {value!r}")
        for name, value in (
            ("total_claims", self.total_claims),
            ("supported_claims", self.supported_claims),
            ("attributed_claims", self.attributed_claims),
        ):
            if isinstance(value, bool) or not isinstance(value, int):
                raise TypeError(f"{name} must be an int, got {type(value).__name__}")
            if value < 0:
                raise ValueError(f"{name} must be >= 0, got {value}")
        if self.total_claims != len(self.claims):
            raise ValueError("total_claims must equal len(claims)")
        if self.supported_claims > self.total_claims:
            raise ValueError("supported_claims cannot exceed total_claims")
        if self.attributed_claims > self.total_claims:
            raise ValueError("attributed_claims cannot exceed total_claims")
        # The counts and the claim list must agree; a hand-built result that
        # disagrees with itself is a bug, not a rounding artefact.
        expected_supported = sum(1 for c in self.claims if c.supported)
        expected_attributed = sum(1 for c in self.claims if c.attributed)
        if self.supported_claims != expected_supported:
            raise ValueError("supported_claims disagrees with the claim list")
        if self.attributed_claims != expected_attributed:
            raise ValueError("attributed_claims disagrees with the claim list")
        for name, rate, count in (
            ("supported_claim_rate", self.supported_claim_rate, self.supported_claims),
            ("attributed_claim_rate", self.attributed_claim_rate, self.attributed_claims),
        ):
            if abs(rate - safe_ratio(count, self.total_claims)) > 1e-9:
                raise ValueError(f"{name} disagrees with the claim counts")

    def to_dict(self) -> dict[str, object]:
        return {
            "supported_claim_rate": self.supported_claim_rate,
            "attributed_claim_rate": self.attributed_claim_rate,
            "mean_support_score": self.mean_support_score,
            "total_claims": self.total_claims,
            "supported_claims": self.supported_claims,
            "attributed_claims": self.attributed_claims,
            "claims": [claim.to_dict() for claim in self.claims],
        }

    def summary(self) -> str:
        """Fixed-format, human-readable block (no timestamp, no paths)."""
        return (
            "## Claim Attribution\n\n"
            f"Claims: {self.total_claims}\n"
            f"Supported: {self.supported_claims}\n"
            f"Attributed: {self.attributed_claims}\n"
            f"Supported claim rate: {self.supported_claim_rate:.6f}\n"
            f"Attributed claim rate: {self.attributed_claim_rate:.6f}\n"
            f"Mean support score: {self.mean_support_score:.6f}\n"
        )


class ClaimExtractor(ABC):
    """Turns an answer into its claims."""

    @abstractmethod
    def extract(self, answer: str) -> tuple[Claim, ...]:
        """Return the claims of ``answer``, in the order they appear."""


class DeterministicClaimExtractor(ClaimExtractor):
    """Sentence-level claim extraction. Deterministic, no model, no NLP.

    One non-empty sentence is one claim. Nothing is decomposed further: a
    sentence "combining two facts" stays one claim, and a sentence fragment
    stays a claim of its own. That is the whole extractor, and it is the honest
    ceiling of a baseline with no clause segmentation and no coreference.
    """

    def extract(self, answer: str) -> tuple[Claim, ...]:
        if not isinstance(answer, str):
            raise TypeError(f"answer must be a str, got {type(answer).__name__}")
        return tuple(
            Claim(claim_id=f"claim-{index}", text=sentence, sentence_index=index)
            for index, sentence in enumerate(split_sentences(answer))
        )


class ClaimAttributor(ABC):
    """Scores claims against the available evidence and the cited sources."""

    @abstractmethod
    def attribute(
        self,
        claims: Sequence[Claim],
        *,
        context: Context,
        citations: tuple[Citation, ...] = (),
    ) -> AttributionResult:
        """Return per-claim support and attribution for ``claims``."""


class DeterministicClaimAttributor(ClaimAttributor):
    """Lexical claim attribution: token overlap against context and citations.

    For each claim, the score is the share of its unique tokens found in the
    context text; the claim is ``supported`` when that score reaches
    ``threshold``. Each citation is scored the same way against the claim, and
    every citation that reaches the threshold is listed as a supporting source
    -- in citation input order, so the caller's ranking is never re-sorted.

    No entailment, no negation handling, no paraphrase matching: a claim that
    says the opposite of its source with the same words scores identically to
    the source's own wording. That limitation is the baseline's, and it is
    recorded in the evidence rather than hidden behind a confident-looking
    number.
    """

    def __init__(
        self,
        *,
        tokenizer: Tokenizer | None = None,
        threshold: float = DEFAULT_ATTRIBUTION_THRESHOLD,
    ) -> None:
        self.tokenizer = tokenizer if tokenizer is not None else SimpleTokenizer()
        if not isinstance(self.tokenizer, Tokenizer):
            raise TypeError(
                f"tokenizer must be a Tokenizer, got {type(self.tokenizer).__name__}"
            )
        if isinstance(threshold, bool) or not isinstance(threshold, (int, float)):
            raise TypeError(f"threshold must be a number, got {type(threshold).__name__}")
        if not 0.0 < threshold <= 1.0:
            raise ValueError(f"threshold must be in (0, 1], got {threshold!r}")
        self.threshold = float(threshold)

    def attribute(
        self,
        claims: Sequence[Claim],
        *,
        context: Context,
        citations: tuple[Citation, ...] = (),
    ) -> AttributionResult:
        """Score every claim against ``context`` and ``citations``.

        The context is required: ``supported`` is measured against the evidence
        retrieval produced, which is what makes it a different question from
        ``attributed`` (measured against the citations alone).
        """
        if not isinstance(context, Context):
            raise TypeError(f"context must be a Context, got {type(context).__name__}")
        claim_list = list(claims)
        for claim in claim_list:
            if not isinstance(claim, Claim):
                raise TypeError(
                    f"each claim must be a Claim, got {type(claim).__name__}"
                )
        if not isinstance(citations, tuple):
            raise TypeError(
                f"citations must be a tuple of Citation, got {type(citations).__name__}"
            )
        for citation in citations:
            if not isinstance(citation, Citation):
                raise TypeError(
                    f"each citation must be a Citation, got {type(citation).__name__}"
                )

        support_tokens = tokenize_text(context.text, self.tokenizer)
        sources = [
            (citation.chunk_id, tokenize_text(citation.text, self.tokenizer))
            for citation in _unique_citations(citations)
        ]

        attributions = []
        for claim in claim_list:
            tokens = tokenize_text(claim.text, self.tokenizer)
            score = token_coverage(tokens, support_tokens)
            supporting = tuple(
                citation_id
                for citation_id, citation_tokens in sources
                if token_coverage(tokens, citation_tokens) >= self.threshold
            )
            attributions.append(
                ClaimAttribution(
                    claim_id=claim.claim_id,
                    supported=score >= self.threshold,
                    supporting_citation_ids=supporting,
                    support_score=score,
                )
            )

        claims_tuple = tuple(attributions)
        supported_claims = sum(1 for claim in claims_tuple if claim.supported)
        attributed_claims = sum(1 for claim in claims_tuple if claim.attributed)
        total_claims = len(claims_tuple)
        return AttributionResult(
            claims=claims_tuple,
            supported_claim_rate=safe_ratio(supported_claims, total_claims),
            attributed_claim_rate=safe_ratio(attributed_claims, total_claims),
            total_claims=total_claims,
            supported_claims=supported_claims,
            attributed_claims=attributed_claims,
            mean_support_score=safe_ratio(
                sum(claim.support_score for claim in claims_tuple), total_claims
            ),
        )


def _unique_citations(citations: Sequence[Citation]) -> list[Citation]:
    """Citations in input order, duplicates collapsed to the first occurrence.

    Same rule ``citations_from_context`` uses for chunk ids: attribution keeps
    the caller's order rather than re-ranking it, and the same source is never
    listed twice.
    """
    seen: set[str] = set()
    out: list[Citation] = []
    for citation in citations:
        if citation.chunk_id in seen:
            continue
        seen.add(citation.chunk_id)
        out.append(citation)
    return out
